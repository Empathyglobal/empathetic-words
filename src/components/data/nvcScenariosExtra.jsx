export function getScenarioMeta(id) {
  return SCENARIO_META[id] || { type: "school", difficulty: "easy", tags: [] };
}

export function sortScenariosByTypeThenTitle(scenarios) {
  return [...scenarios].sort((a, b) => {
    const metaA = getScenarioMeta(a.id);
    const metaB = getScenarioMeta(b.id);
    
    const typeIndexA = SCENARIO_TYPE_ORDER.indexOf(metaA.type);
    const typeIndexB = SCENARIO_TYPE_ORDER.indexOf(metaB.type);
    
    if (typeIndexA !== typeIndexB) {
      return typeIndexA - typeIndexB;
    }
    
    return a.title.localeCompare(b.title);
  });
}

export function filterScenariosByType(scenarios, type) {
  if (type === "all") return scenarios;
  return scenarios.filter(s => getScenarioMeta(s.id).type === type);
}
